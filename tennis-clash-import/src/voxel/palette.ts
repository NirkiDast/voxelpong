/** A palette with colours in the renderer's linear working space, ready for vertex colours. */
export class Palette {
  private readonly linear: THREE.Color[] = [];
  private readonly hex: number[] = [];

  constructor(overrides: Partial<Record<number, number>> = {}) {
    for (let i = 0; i < PALETTE_SIZE; i++) {
      const hex = overrides[i] ?? BASE[i] ?? 0xff00ff;
      this.hex[i] = hex;
      this.linear[i] = new THREE.Color().setHex(hex);
    }
  }

  color(i: PaletteIndex): THREE.Color {
    return this.linear[i] ?? this.linear[0];
  }

  hexOf(i: PaletteIndex): number {
    return this.hex[i] ?? 0xff00ff;
  }

  /** The same palette with the accent slots swapped (one per tour). */
  withAccent(accent: number, accentDark: number): Palette {
    return new Palette({ ...this.overrides(), [PAL.accent]: accent, [PAL.accentDark]: accentDark });
  }

  private overrides(): Record<number, number> {
    const o: Record<number, number> = {};
    this.hex.forEach((h, i) => (o[i] = h));
    return o;
  }
}

export const DEFAULT_PALETTE = new Palette();
